const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const vm = require('node:vm');
const ts = require('./ci/transpile-arkts.cjs');
const code = ts.transpileModule(fs.readFileSync('cexing/entry/src/main/ets/lib/RuleDnsForms.ets','utf8')).outputText;
const host = { exports: {}, require: () => ({}) }; vm.runInNewContext(code,host);
const f=host.exports.RuleDnsForms;
const item={id:'rule-id',revision:'rule-revision'};
const target={item:{id:'dns-id',revision:'dns-revision',fields:{nameserver:'existing-fingerprint'}},value:{nameserver:['https://old.test/dns-query'],listen:'127.0.0.1:1053','x-advanced':{keep:true}}};
const rule={type:'IP-CIDR',condition:'192.0.2.0/24',target:'manual',noResolve:true};
assert.equal(f.ruleValue(rule),'IP-CIDR,192.0.2.0/24,manual,no-resolve');
assert.equal(f.parseRule(f.ruleValue(rule)).noResolve,true);
assert.equal(f.parseRule('AND,((DOMAIN,test),(NETWORK,tcp)),manual'),null,'advanced syntax must not be split or lost');
assert.equal(f.addRule('add',{...rule,noResolve:false},'match-id').before,'match-id');
assert.throws(()=>f.addRule('add',{...rule,type:'MATCH'},'match-id'),/最终/);
assert.throws(()=>f.moveRule('move',{id:'match-id'},'rule-id','match-id'),/末尾/);
assert.throws(()=>f.moveRule('move',item,'','match-id'),/末尾/);
assert.equal(f.moveRule('move',item,'match-id','match-id').before,'match-id');
assert.throws(()=>f.ruleValue({...rule,target:'manual,REJECT'}),/填写/);
const preset=f.recommendedDns(target);
assert.deepEqual(Object.keys(preset.patch).sort(),['default-nameserver','nameserver']);
assert.equal(preset.preconditions.nameserver,'existing-fingerprint');
assert.equal(preset.preconditions['default-nameserver'],crypto.createHash('sha256').update('missing field').digest('hex'));
assert.ok(!('listen' in preset.patch)); assert.ok(!('rules' in preset.patch));
assert.equal(f.withoutPreset([preset,{id:'unrelated'}]).length,1);
assert.throws(()=>f.advancedPatch('advanced','dns',target,'{"listen":"0.0.0.0:53"}'),/系统/);
const advanced=f.advancedPatch('advanced','dns',target,JSON.stringify({...target.value,'nameserver-policy':{'public.test':'https://dns.test/dns-query'}}));
assert.ok(!('x-advanced' in advanced.patch),'field patch preserves unedited keys');
assert.throws(()=>f.providerValue({name:'a',type:'http',behavior:'classical',format:'mrs',location:'https://public.test/rules',interval:60}),/类型/);
assert.throws(()=>f.providerValue({name:'a',type:'file',behavior:'domain',format:'yaml',location:'../secret',interval:0}),/相对/);
assert.equal(f.advancedRule('raw',{item},'AND,((DOMAIN,test),(NETWORK,tcp)),manual').expected,'rule-revision');
assert.equal(f.deleteItem('del','hosts',item).expected,'rule-revision');
console.log('PASS: actual rule/provider/DNS forms, MATCH anchors, injection rejection, unknown advanced fields, preset undo and protected listener');
